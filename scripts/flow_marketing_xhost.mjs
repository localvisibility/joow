import { chromium, devices } from 'playwright';
const out = process.env.OUT;
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', proxy: { server: process.env.HTTPS_PROXY }, args: ['--ignore-certificate-errors'] });
const ctx = await browser.newContext({ ...devices['iPhone 13'], ignoreHTTPSErrors: true });
const page = await ctx.newPage();
await page.goto('https://joow.fr/?utm_source=meta&utm_campaign=test-vitrine&fbclid=TEST123', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/x-home.png` });
await page.fill('.search-shell input', 'Bouillon Chartier Montparnasse');
await page.waitForSelector('.gen-results:not(.hidden) button, .gen-results:not(.hidden) [role=option], .gen-results:not(.hidden) a', { timeout: 15000 });
const first = await page.$('.gen-results button, .gen-results [role=option], .gen-results a');
console.log('first result:', (await first.innerText()).replace(/\n/g, ' | '));
await first.click();
await page.waitForTimeout(400);
await Promise.all([page.waitForNavigation({ timeout: 60000 }), page.click('.search-shell ~ * button[type=submit], form button[type=submit]')]);
console.log('landed on:', page.url());
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/x-landed.png` });
await browser.close();
